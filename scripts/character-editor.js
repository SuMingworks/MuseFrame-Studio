      function uniqueParts(parts) {
        const seen = new Set();
        const out = [];
        for (let item of parts) {
          if (!item || !String(item).trim()) continue;
          item = String(item)
            .trim()
            .replace(/[。；]+$/, '');
          const key = item.replace(/[\s，。；：、]/g, '');
          if (seen.has(key)) continue;
          seen.add(key);
          out.push(item);
        }
        return out;
      }
