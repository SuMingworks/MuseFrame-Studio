import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const directory = new URL('../data/characters/', import.meta.url);
const readJson = (name) => JSON.parse(readFileSync(new URL(name, directory), 'utf8'));
const index = readJson('index.json');
const ids = readdirSync(directory, { withFileTypes: true })
  .filter((entry) => entry.isFile() && entry.name.endsWith('.json') && entry.name !== 'index.json')
  .map((entry) => entry.name.slice(0, -5))
  .sort();
const records = new Map(ids.map((id) => {
  if (!/^[a-zA-Z][a-zA-Z0-9_-]*$/.test(id)) {
    throw new Error(`Invalid character ID: ${id}`);
  }
  const record = readJson(`${id}.json`);
  if (typeof record?.plan?.label !== 'string' || !record.plan.label.trim()) {
    throw new Error(`${id}.json requires a non-empty plan.label`);
  }
  return [id, record];
}));

function completeOrder(key) {
  const ordered = index[key];
  if (!Array.isArray(ordered) || new Set(ordered).size !== ordered.length) {
    throw new Error(`index.json: ${key} must be an array of unique IDs`);
  }
  for (const id of ordered) {
    if (!records.has(id)) throw new Error(`index.json: ${key} references missing character ${id}`);
  }
  const listed = new Set(ordered);
  return [...ordered, ...ids.filter((id) => !listed.has(id))];
}

const presetOrder = completeOrder('presetOrder');
const cardOrder = completeOrder('cardOrder');
const library = Object.fromEntries(presetOrder.map((id) => [id, records.get(id)]));
const output = new URL('./character-library.js', import.meta.url);
const content = '// Generated by scripts/build-character-library.mjs from data/characters/.\n'
  + `const characterLibrary = ${JSON.stringify(library, null, 2)};\n`
  + `const characterCardOrder = ${JSON.stringify(cardOrder, null, 2)};\n`;

if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== content) {
    throw new Error('Character library is out of date. Run node scripts/build-character-library.mjs.');
  }
} else {
  writeFileSync(output, content);
  console.log(`Generated character library with ${presetOrder.length} presets.`);
}
